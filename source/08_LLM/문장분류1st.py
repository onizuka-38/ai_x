import os
import pandas as pd
import random
from openai import OpenAI
from dotenv import load_dotenv

load_dotenv()
client = OpenAI(
  api_key=os.environ.get("OPENAI_API_KEY"),
)

# 캡틴의 요청대로 파일 경로 유지
df = pd.read_csv("data/samples.csv")
TEST_COUNT = 20
success = 0

for i,count in enumerate(range(TEST_COUNT)):
    # 캡틴의 요청대로 인덱스 범위 유지
    random_index = random.randrange(1,16542)
    response = client.responses.create(
        model="gpt-4o",
        # 캡틴의 요청대로 temperature 유지
        temperature=0.4,
        instructions="""[역할]
당신은 최고의 한국어 문장 분석 AI입니다. 당신의 임무는 문장의 피상적인 뉘앙스가 아닌, 아래의 '절대 규칙'과 '분류 기준'에 따라 문장을 ‘유형,극성,시제,확실성’으로 정밀하게 분류하는 것입니다.

[절대 규칙: 황금률]
**모든 분류(유형, 시제, 극성, 확실성)는 반드시 문장의 주어와 서술어, 즉 '주요 절(Main Clause)'을 기준으로 판단해야 합니다.** 인용문("...")이나 종속절의 내용에 현혹되지 마십시오.
- 예시: `"...할 예정이다"라고 발표했다.` -> 이 문장의 핵심은 '예정'이 아니라 과거에 '발표했다'는 사실입니다. 따라서 '사실형, 과거'입니다.

[분류 기준]

1.  **유형 판단**
    * **사실형**: 객관적 사건, 정보, 상태를 전달. 누군가의 발언을 전달하는 문장(`"...라고 말했다"`)은 '대화형'이 아닌 '사실형'입니다. 어떤 사물의 특징이나 구성 요소를 설명하는 문장(`~를 갖췄다`)도 '사실형'입니다.
    * **추론형**: 사실을 기반으로 한 해석, 평가, 의견. `분위기가 달라지고 있다`처럼 관찰자의 주관적 해석이 들어간 문장은 '추론형'입니다.
    * **예측형**: 미래에 대한 전망, 계획, 예보.
    * **대화형**: 인용 보도가 아닌, 직접적인 대화나 구어체 문장.

2.  **극성 (긍정/부정) 판단**
    * **긍정**: 어떤 행위나 상태가 '발생했음' 또는 '존재함'을 서술하면 '긍정'입니다. **'부인했다', '거절했다', '의혹' 등 부정적 뉘앙스의 단어가 포함되어도, 그 '부인하는 행위' 자체가 발생한 사실이므로 문장은 '긍정'입니다.**
    * **부정**: `~않다`, `~못했다`, `없다`, `아니다` 등 명시적인 문법적 부정이 사용될 때만 해당됩니다.

3.  **시제 판단**
    * **핵심 동사**의 시제를 따릅니다.
    * **현재 상태 묘사**: 과거형 동사(`~했다`, `갖췄다`)를 사용했더라도, 그것이 현재 존재하는 사물의 특징이나 상태를 설명하는 것이라면 '현재'로 판단합니다.
    * **지식/정보**: 어떤 사실이 '알려져 있다', '정의된다' 등 보편적 지식을 설명하는 문장은 '현재'로 봅니다. (과거에 알려졌어도 현재 유효한 지식이므로)

[출력 형식]
* `유형,극성,시제,확실성` 형식만 사용하며, 다른 어떤 설명도 추가하지 마십시오.

[특별 학습 예시 (오답 교정용)]
입력: 기업은행 관계자는 "취임식을 비롯한 윤 행장의 향후 일정은 정해지지 않았다"고 말했다.
출력: 사실형,긍정,과거,확실 (해설: 핵심은 과거에 '말했다'는 사실. 인용문의 부정적 내용('정해지지 않았다')은 극성 판단에 영향을 주지 않음.)

입력: A씨는 자신의 근무태만과 관련한 의혹도 부인했다.
출력: 사실형,긍정,과거,확실 (해설: '부인'이라는 부정적 단어가 있지만, '부인하는 행위'가 일어났다는 사실을 긍정하므로 '긍정'임.)

입력: 지난 23일, 이더리움 재단은 공식 블로그를 통해 블록높이 9,200,000에서 뮤어빙하 업그레이드를 진행할 예정이라고 발표한 바 있다.
출력: 사실형,긍정,과거,확실 (해설: 핵심은 과거에 '발표한 바 있다'는 사실. 발표 내용인 '예정'에 현혹되면 안 됨.)

입력: 요즘은 분위기가 달라지고 있다.
출력: 추론형,긍정,현재,확실 (해설: '분위기 변화'는 객관적 사실이 아닌 관찰자의 해석이므로 '추론형'임.)

입력: 전투와 모험이라는 이용자 선택에 따라 성장 방향을 결정할 수 있는 '만다라' 시스템과 대규모 전투 콘텐츠, 화신, 탈것 등에 이르는 각종 성장 요소를 갖췄다.
출력: 사실형,긍정,현재,확실 (해설: '갖췄다'는 과거형이지만, 현재 시스템이 보유한 특징(상태)을 설명하므로 '현재'임.)
""",
        input=df.iloc[random_index]['user_prompt'],
    )
    answer = str(df.iloc[random_index,1])+','+str(df.iloc[random_index,2])+','+str(df.iloc[random_index,3])+','+str(df.iloc[random_index,4])
    if response.output_text.strip() != answer:
        print(f'{count+1}:',df.iloc[random_index]['user_prompt'])
        print('정답:',answer)
        print('GPT:',response.output_text)
    else:
        success += 1
    
print('정답률:',success/TEST_COUNT)